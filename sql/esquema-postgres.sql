CREATE TABLE usuario (
  id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  nombre VARCHAR(120) NOT NULL,
  correo VARCHAR(254) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  activo SMALLINT NOT NULL DEFAULT 1,
  correo_verificado SMALLINT NOT NULL DEFAULT 0,
  creado_en TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  ultimo_acceso TIMESTAMP(6) NULL,
  PRIMARY KEY (id_usuario),
  CONSTRAINT uq_usuario_1 UNIQUE (correo),
  CONSTRAINT ck_usuario_1 CHECK (correo = LOWER(TRIM(correo)) AND NOT correo ~ '[[:space:]]'),
  CONSTRAINT ck_usuario_2 CHECK (activo IN (0,1)),
  CONSTRAINT ck_usuario_3 CHECK (correo_verificado IN (0,1))
);

CREATE TABLE cliente (
  id_cliente BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  id_usuario BIGINT NULL,
  nombre VARCHAR(120) NOT NULL,
  empresa VARCHAR(180) NULL,
  identificacion VARCHAR(30) NULL,
  correo VARCHAR(254) NOT NULL,
  telefono VARCHAR(30) NOT NULL,
  creado_en TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id_cliente),
  CONSTRAINT uq_cliente_1 UNIQUE (id_usuario)
);

CREATE TABLE rol (
  id_rol INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  codigo VARCHAR(30) NOT NULL,
  nombre VARCHAR(60) NOT NULL,
  descripcion VARCHAR(250) NULL,
  activo SMALLINT NOT NULL DEFAULT 1,
  PRIMARY KEY (id_rol),
  CONSTRAINT uq_rol_1 UNIQUE (codigo),
  CONSTRAINT ck_rol_1 CHECK (activo IN (0,1))
);

CREATE TABLE sesion_usuario (
  id_sesion BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  id_usuario BIGINT NOT NULL,
  token_hash CHAR(64) NOT NULL,
  creado_en TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  expira_en TIMESTAMP(6) NOT NULL,
  revocada_en TIMESTAMP(6) NULL,
  PRIMARY KEY (id_sesion),
  CONSTRAINT uq_sesion_usuario_1 UNIQUE (token_hash),
  CONSTRAINT ck_sesion_usuario_1 CHECK (expira_en > creado_en),
  CONSTRAINT ck_sesion_usuario_2 CHECK (revocada_en >= creado_en)
);

CREATE TABLE usuario_rol (
  id_usuario BIGINT NOT NULL,
  id_rol INT NOT NULL,
