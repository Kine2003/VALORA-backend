import assert from 'node:assert/strict';
import { validarValor, permiteSeccion, listarTabla, modificarTabla } from '../servicios/gestion.js';
import {configuracionDesdeUrl} from '../datos/postgres.js';
import {validarProductos,imagenValida} from '../lib/cart.js';
assert.deepEqual(validarProductos({version:2,moneda:'USD',demostracion:true,productos:[]}),[]);
assert.equal(imagenValida('https://example.invalid/plato.jpg'),true);
assert.equal(imagenValida('https://usuario:clave@example.invalid/plato.jpg'),false);
const entornoAnterior=process.env.NODE_ENV;
process.env.NODE_ENV='production';
assert.equal(configuracionDesdeUrl('postgresql://usuario:clave@host.example/valora?sslmode=disable').ssl.rejectUnauthorized,true);
if(entornoAnterior===undefined)delete process.env.NODE_ENV;else process.env.NODE_ENV=entornoAnterior;
assert.equal(permiteSeccion({roles:['USUARIO']},'inventario'),false);
assert.equal(permiteSeccion({roles:['CATALOGO']},'personas'),false);
assert.equal(permiteSeccion({roles:['CATALOGO']},'cocina'),true);
assert.equal(permiteSeccion({roles:['ADMINISTRADOR']},'finanzas'),true);
assert.throws(()=>validarValor({nombre:'activo',tipo:'smallint'},'false'));
assert.throws(()=>validarValor({nombre:'precio',tipo:'numeric',escala:2},'NaN'));
assert.throws(()=>validarValor({nombre:'precio',tipo:'numeric',escala:2},'1.123'));
assert.throws(()=>validarValor({nombre:'imagen',tipo:'text'},'javascript:alert(1)'));
assert.throws(()=>validarValor({nombre:'fecha',tipo:'date'},'2026-02-30'));
assert.equal(validarValor({nombre:'precio',tipo:'numeric',escala:2},'12.50'),'12.50');
assert.equal(validarValor({nombre:'nombre',tipo:'text'},'<b>Texto</b>'),'<b>Texto</b>');
const db={query(){throw Error('No debe consultar SQL con una tabla no permitida');}};
await assert.rejects(listarTabla(db,'usuario; DROP TABLE usuario',{}, {roles:['ADMINISTRADOR']}));
await assert.rejects(modificarTabla(db,'usuario','PATCH',{clave:{id_usuario:1},valores:{password_hash:'x'}},{roles:['USUARIO']}));
console.log('Gestión: permisos, validación estricta y tablas no autorizadas comprobados.');
