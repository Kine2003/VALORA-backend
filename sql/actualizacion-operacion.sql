CREATE TABLE IF NOT EXISTS operacion_cocina (
  id_operacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  referencia VARCHAR(80) NOT NULL UNIQUE,
  tipo VARCHAR(12) NOT NULL CHECK (tipo IN ('COMPRA','PRODUCCION','RECETA','PLATO')),
  id_usuario BIGINT NOT NULL REFERENCES usuario(id_usuario),
  datos JSONB NOT NULL,
  resultado JSONB NOT NULL,
  fecha TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
