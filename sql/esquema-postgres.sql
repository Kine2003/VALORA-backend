      OR (tipo_linea = 'ENTREGA' AND id_solicitud_entrega IS NOT NULL AND id_detalle_solicitud IS NULL AND cantidad = 1)),
  CONSTRAINT ck_detalle_factura_5 CHECK (precio_unitario_centavos >= 0),
  CONSTRAINT ck_detalle_factura_6 CHECK (descuento_centavos >= 0)
