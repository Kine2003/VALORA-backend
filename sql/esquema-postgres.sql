CREATE TABLE contrato (
  id_contrato BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  codigo VARCHAR(60) NOT NULL,
  id_cliente BIGINT NOT NULL,
  fecha_inicio DATE NOT NULL,
  fecha_fin DATE NOT NULL,
  estado VARCHAR(12) NOT NULL,
  entrega VARCHAR(10) NOT NULL,
  direccion_servicio VARCHAR(500) NULL,
  id_registrado_por BIGINT NOT NULL,
  observaciones TEXT NULL,
  creado_en TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id_contrato),
  CONSTRAINT uq_contrato_1 UNIQUE (codigo),
  CONSTRAINT ck_contrato_1 CHECK (fecha_fin >= fecha_inicio),
  CONSTRAINT ck_contrato_2 CHECK (estado IN ('BORRADOR','VIGENTE','SUSPENDIDO','FINALIZADO','CANCELADO')),
  CONSTRAINT ck_contrato_3 CHECK (entrega IN ('RETIRO','DOMICILIO')),
  CONSTRAINT ck_contrato_4 CHECK (entrega <> 'DOMICILIO' OR NULLIF(TRIM(direccion_servicio),'') IS NOT NULL)
);

CREATE TABLE solicitud (
  id_solicitud BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  id_cliente BIGINT NOT NULL,
  id_servicio VARCHAR(80) NULL,
  id_tipo_comida INT NULL,
  id_gestionado_por BIGINT NULL,
  id_solicitud_origen BIGINT NULL,
  tipo VARCHAR(10) NOT NULL,
  estado VARCHAR(12) NOT NULL,
  fecha_evento DATE NULL,
  hora_evento CHAR(5) NULL,
  personas BIGINT NULL,
  entrega VARCHAR(10) NULL,
  direccion VARCHAR(500) NULL,
  mensaje TEXT NULL,
  id_servicio_contratado BIGINT NULL,
  costo_entrega_centavos DECIMAL(14,0) NOT NULL DEFAULT 0,
  estado_pago VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE_PAGO',
  metodo_pago VARCHAR(20) NULL,
  pagado_en TIMESTAMP(6) NULL,
  referencia_pago VARCHAR(100) NULL,
  creado_en TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  inventario_descontado_en TIMESTAMP(6) NULL,
  PRIMARY KEY (id_solicitud),
  CONSTRAINT ux_sol_serv_fecha UNIQUE (id_servicio_contratado, fecha_evento),
  CONSTRAINT ck_solicitud_1 CHECK (estado IN ('NUEVA','EN_REVISION','COTIZADA','CONFIRMADA','EN_PROCESO','ENTREGADA','RECHAZADA','CANCELADA')),
  CONSTRAINT ck_solicitud_2 CHECK (entrega IN ('RETIRO','DOMICILIO')),
  CONSTRAINT ck_solicitud_3 CHECK (entrega <> 'DOMICILIO' OR NULLIF(TRIM(direccion),'') IS NOT NULL),
  CONSTRAINT ck_solicitud_4 CHECK (entrega <> 'RETIRO' OR costo_entrega_centavos = 0),
  CONSTRAINT ck_solicitud_5 CHECK (personas > 0),
  CONSTRAINT ck_solicitud_6 CHECK ((tipo = 'COTIZACION' AND id_servicio IS NOT NULL AND id_servicio_contratado IS NULL AND id_solicitud_origen IS NULL)
      OR (tipo = 'PEDIDO' AND id_servicio IS NULL AND id_tipo_comida IS NULL AND personas IS NULL
          AND fecha_evento IS NOT NULL AND hora_evento IS NOT NULL AND entrega IS NOT NULL)),
  CONSTRAINT ck_solicitud_7 CHECK (hora_evento ~ '^([01][0-9]|2[0-3]):[0-5][0-9]$'),
  CONSTRAINT ck_solicitud_8 CHECK (costo_entrega_centavos >= 0),
  CONSTRAINT ck_solicitud_9 CHECK (estado_pago IN ('PENDIENTE_PAGO','PAGO_EN_REVISION','PAGADO'))
);

